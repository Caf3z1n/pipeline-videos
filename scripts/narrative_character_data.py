from __future__ import annotations

from typing import Literal, TypedDict

NarrativeRole = Literal[
    "story_context",
    "parallel_account",
    "character_background",
    "character_development",
    "character_outcome",
    "direct_speech",
]


class RelatedSpec(TypedDict):
    code: str
    reference: str
    role: NarrativeRole


class NarrativeStorySpec(TypedDict):
    story_id: str
    title: str
    characters: list[str]
    aliases: list[str]
    code: str
    anchor: str
    context: str
    central_theme: str
    human_conflict: str
    reveal: str
    related: list[RelatedSpec]


def related(code: str, reference: str, role: NarrativeRole) -> RelatedSpec:
    return {"code": code, "reference": reference, "role": role}


def story(
    story_id: str,
    title: str,
    characters: list[str],
    aliases: list[str],
    code: str,
    anchor: str,
    context: str,
    central_theme: str,
    human_conflict: str,
    reveal: str,
    passages: list[RelatedSpec],
) -> NarrativeStorySpec:
    return {
        "story_id": story_id,
        "title": title,
        "characters": characters,
        "aliases": aliases,
        "code": code,
        "anchor": anchor,
        "context": context,
        "central_theme": central_theme,
        "human_conflict": human_conflict,
        "reveal": reveal,
        "related": passages,
    }


